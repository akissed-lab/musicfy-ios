package com.music.innertube.models

import kotlinx.serialization.Serializable

/** Request bodies for the three Innertube endpoints the iOS lyrics port uses. */
@Serializable
data class PlayerBody(
    val context: Context,
    val videoId: String,
    val playlistId: String? = null,
    val contentCheckOk: Boolean = true,
    val racyCheckOk: Boolean = true,
)

@Serializable
data class BrowseBody(
    val context: Context,
    val browseId: String? = null,
    val params: String? = null,
    val continuation: String? = null,
)

@Serializable
data class NextBody(
    val context: Context,
    val videoId: String?,
    val playlistId: String? = null,
    val playlistSetVideoId: String? = null,
    val index: Int? = null,
    val params: String? = null,
    val continuation: String? = null,
)

@Serializable
data class GetTranscriptBody(val context: Context, val params: String)

/** Only the fields of each response that the lyrics providers read. */
@Serializable
data class GetTranscriptResponse(val actions: List<Action>? = null) {
    @Serializable
    data class Action(val updateEngagementPanelAction: UpdateEngagementPanelAction? = null) {
        @Serializable
        data class UpdateEngagementPanelAction(val content: Content? = null) {
            @Serializable
            data class Content(val transcriptRenderer: TranscriptRenderer? = null) {
                @Serializable
                data class TranscriptRenderer(val body: Body? = null) {
                    @Serializable
                    data class Body(val transcriptBodyRenderer: TranscriptBodyRenderer? = null) {
                        @Serializable
                        data class TranscriptBodyRenderer(val cueGroups: List<CueGroup>? = null) {
                            @Serializable
                            data class CueGroup(val transcriptCueGroupRenderer: TranscriptCueGroupRenderer? = null) {
                                @Serializable
                                data class TranscriptCueGroupRenderer(val cues: List<Cue>? = null) {
                                    @Serializable
                                    data class Cue(val transcriptCueRenderer: TranscriptCueRenderer? = null) {
                                        @Serializable
                                        data class TranscriptCueRenderer(
                                            val cue: SimpleText? = null,
                                            val startOffsetMs: Long = 0,
                                        ) {
                                            @Serializable
                                            data class SimpleText(val simpleText: String = "")
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
        }
    }
}

@Serializable
data class BrowseResponse(val contents: Contents? = null) {
    @Serializable
    data class Contents(val sectionListRenderer: SectionListRenderer? = null)

    @Serializable
    data class SectionListRenderer(val contents: List<Content>? = null)

    @Serializable
    data class Content(val musicDescriptionShelfRenderer: MusicDescriptionShelfRenderer? = null)

    @Serializable
    data class MusicDescriptionShelfRenderer(val description: Runs? = null)

    @Serializable
    data class Runs(val runs: List<Run>? = null)

    @Serializable
    data class Run(val text: String = "")
}

@Serializable
data class PlayerResponse(val captions: Captions? = null) {
    @Serializable
    data class Captions(val playerCaptionsTracklistRenderer: PlayerCaptionsTracklistRenderer? = null) {
        @Serializable
        data class PlayerCaptionsTracklistRenderer(val captionTracks: List<CaptionTrack>? = null)

        @Serializable
        data class CaptionTrack(
            val baseUrl: String,
            val languageCode: String? = null,
            /** "asr" for auto-generated captions, absent for uploaded ones */
            val kind: String? = null,
        ) {
            val isAutoGenerated: Boolean get() = kind == "asr"
        }
    }
}

@Serializable
data class NextResponse(val contents: Contents? = null) {
    @Serializable
    data class Contents(val singleColumnMusicWatchNextResultsRenderer: SingleColumnMusicWatchNextResultsRenderer? = null) {
        @Serializable
        data class SingleColumnMusicWatchNextResultsRenderer(val tabbedRenderer: TabbedRenderer? = null) {
            @Serializable
            data class TabbedRenderer(val watchNextTabbedResultsRenderer: WatchNextTabbedResultsRenderer? = null) {
                @Serializable
                data class WatchNextTabbedResultsRenderer(val tabs: List<Tab>? = null) {
                    @Serializable
                    data class Tab(val tabRenderer: TabRenderer? = null) {
                        @Serializable
                        data class TabRenderer(val endpoint: NavigationEndpoint? = null)
                    }
                }
            }
        }
    }

    @Serializable
    data class NavigationEndpoint(val browseEndpoint: BrowseEndpoint? = null)
}
