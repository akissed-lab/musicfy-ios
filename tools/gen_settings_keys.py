#!/usr/bin/env python3
"""Generate SettingsKeys.kt from upstream PreferenceKeys.kt.

Upstream declares 321 typed DataStore keys. The iOS port stores the same keys
as plain strings in NSUserDefaults; typed access lives in SettingsStore.kt.
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "reference" / "app" / "kotlin" / "com" / "example" / "musicfy" / "constants" / "PreferenceKeys.kt"
TARGET = ROOT / "composeApp" / "src" / "commonMain" / "kotlin" / "com" / "example" / "musicfy" / "settings" / "SettingsKeys.kt"

PATTERN = re.compile(
    r'val\s+(\w+)\s*=\s*(boolean|int|long|float|string)PreferencesKey\("([^"]+)"\)'
)

TYPE_CODES = {
    "boolean": "b",
    "int": "i",
    "long": "l",
    "float": "f",
    "string": "s",
}


def main() -> None:
    text = SOURCE.read_text(encoding="utf-8")
    pairs = PATTERN.findall(text)
    seen: set[str] = set()
    seen_keys: set[str] = set()
    seen_type_keys: set[str] = set()
    types: dict[str, str] = {}
    lines = [
        "// Generated by tools/gen_settings_keys.py from upstream PreferenceKeys.kt.",
        "// Do not edit by hand; regenerate after upstream updates.",
        "package com.example.musicfy.settings",
        "",
        "object SettingsKeys {",
    ]
    for name, kind, key in pairs:
        if name in seen:
            continue
        seen.add(name)
        types[name] = TYPE_CODES[kind]
        lines.append(f'    const val {name} = "{key}"')
    lines.append("")
    lines.append("    val AllKeys = listOf(")
    for name, _, key in pairs:
        if key in seen_keys:
            continue
        seen_keys.add(key)
        lines.append(f'        "{key}",')
    lines.append("    )")
    lines.append("")
    lines.append("    val KeyTypes = mapOf(")
    for name, _, key in pairs:
        if key in seen_type_keys:
            continue
        seen_type_keys.add(key)
        lines.append(f'        "{key}" to "{types[name]}",')
    lines.append("    )")
    lines += ["}", ""]
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"generated {len(seen)} keys -> {TARGET}")


if __name__ == "__main__":
    main()
